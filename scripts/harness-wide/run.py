#!/usr/bin/env python3
"""The exact harness of the loops, run wide: four batteries over check.py.

    python3 scripts/harness-wide/run.py --bin PATH            the four batteries
    python3 scripts/harness-wide/run.py --bin PATH --only b,d two of them
    python3 scripts/harness-wide/run.py --bin PATH --quick    a taste, few instances
    sdcpi test harness-wide --bin PATH                        the same through the binary

What is run. The harness `scripts/loops/check.py` (its docstring says what
it checks: the enclosure of the two bounds at every reachable choice
state, the optima and the bounds at the start against an exact backward
induction in rationals, the status and the box of the frontier, the
directed frontier against an exact oracle for several subsets of maximized
components, and the gap test on the instances without choices) is run,
unchanged, over four batteries, the random ones generated by
`scripts/loops/gen.py` from fixed seeds so that every run meets the same
instances:

  a  the hand-written instances of check.py, 3 direction subsets, K in 1..3
  b  200 random instances, tasks 3-6, impacts 1-3, loops 0-3, choices 0-4,
     seed 101, 2 direction subsets, K in 1..2; the oracle of the directed
     frontier is capped at 300 vectors per set here (`--set-cap` of
     check.py, 4000 elsewhere): at 4000 the oracle of b-101-123 at K=2
     maximizing `a` folds sets of some hundred thousand vectors with a
     quadratic reduction and did not finish in an hour; at 300 the
     instance is skipped for that subset in seconds
  c  60 random instances, tasks 3-5, impacts 1-2, loops 1-2, choices 1-3,
     seed 202, 2 direction subsets, K in 1..3 (K=3 is slow on some: a
     timeout is a skip, and the instance is named)
  d  40 random instances without choices, tasks 3-6, impacts 1-3, loops
     1-3, seed 303, K in 1..2, the gap test at K in 1..5

The summary of every battery is read from the report.json check.py writes:
the checks made per kind, the failures with the text of the instance and
the detail line, the skips with their reason, and whether the oracle of the
directed frontier ran (the `dir-frontier` comparisons made). The totals
over the four batteries are printed last: checks, passed, failed, skipped.
A check is one count of the harness; a failure is one failure line; a skip
is one skip line (a timeout of the binary, an exact pass over the cap). The
`passed` figure is checks less failures: the harness counts a check before
it can still skip it, so a skipped check sits among the checks made and is
listed apart, never as a failure.

Options: `--bin PATH` the binary (or SDCPI_BIN); `--work DIR` where the
instances, the YAML, the JSON and the reports go (default `work/` beside
this file); `--jobs N` the parallel instances of the big batteries (default
6, the hand battery uses the same, the K=3 battery at most 4); `--timeout`
scales nothing, every battery carries its own as stated above, unless
`--timeout S` is given, which sets all four; `--only a,b,c,d` a subset;
`--quick` ten instances per random battery; `--resume` keeps the
report of a battery already in the work folder and only runs the others,
so that a run cut short is completed and the summary rebuilt.

The exit code is 0 exactly when no check of any battery failed, 2 when the
run cannot start.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOOPS = HERE.parent / "loops"
CHECK = LOOPS / "check.py"
GEN = LOOPS / "gen.py"

BATTERIES = {
    "a": {
        "title": "the hand-written instances, 3 directions, K 1-3",
        "gen": None,
        "check": ["--hand", "--directions", "3", "--k", "1-3"],
        "timeout": 600,
        "jobs": None,
    },
    "b": {
        "title": "200 random, tasks 3-6, impacts 1-3, loops 0-3, choices 0-4, seed 101, 2 directions, K 1-2",
        "gen": ["--tasks", "3-6", "--impacts", "1-3", "--loops", "0-3", "--choices", "0-4", "--seed", "101", "--count", "200", "--prefix", "b"],
        "check": ["--no-hand", "--directions", "2", "--k", "1-2"],
        "timeout": 300,
        "jobs": None,
        "set_cap": 300,
    },
    "c": {
        "title": "60 random, tasks 3-5, impacts 1-2, loops 1-2, choices 1-3, seed 202, 2 directions, K 1-3",
        "gen": ["--tasks", "3-5", "--impacts", "1-2", "--loops", "1-2", "--choices", "1-3", "--seed", "202", "--count", "60", "--prefix", "c"],
        "check": ["--no-hand", "--directions", "2", "--k", "1-3"],
        "timeout": 600,
        "jobs": 4,
    },
    "d": {
        "title": "40 random without choices, tasks 3-6, impacts 1-3, loops 1-3, seed 303, K 1-2, gap K 1-5",
        "gen": ["--tasks", "3-6", "--impacts", "1-3", "--loops", "1-3", "--choices", "0", "--seed", "303", "--count", "40", "--prefix", "d"],
        "check": ["--no-hand", "--k", "1-2", "--gap-k", "1-5"],
        "timeout": 600,
        "jobs": 4,
    },
}


def sh(cmd: list, log: Path, env: dict) -> int:
    with log.open("w") as f:
        f.write("$ " + " ".join(str(c) for c in cmd) + "\n")
        f.flush()
        p = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, env=env)
    return p.returncode


def run_battery(key: str, spec: dict, args, env: dict) -> dict:
    work = Path(args.work) / f"{key}-{'hand' if spec['gen'] is None else 'random'}"
    work.mkdir(parents=True, exist_ok=True)
    out = {"key": key, "title": spec["title"], "work": str(work)}
    started = time.time()
    paths = []
    rep = work / "report.json"
    if args.resume and rep.exists():
        out["resumed"] = True
        return read_report(out, rep, work, started)
    if spec["gen"] is not None:
        inst = work / "instances"
        gen = spec["gen"][:]
        if args.quick:
            i = gen.index("--count")
            gen[i + 1] = "10"
        rc = sh([sys.executable, str(GEN), *gen, "--out", str(inst)], work / "gen.log", env)
        if rc != 0:
            out["error"] = f"gen.py exit {rc}, see {work / 'gen.log'}"
            return out
        paths = [str(inst)]
    jobs = spec["jobs"] or args.jobs
    if spec["jobs"]:
        jobs = min(spec["jobs"], args.jobs)
    timeout = args.timeout if args.timeout else spec["timeout"]
    set_cap = args.set_cap if args.set_cap else spec.get("set_cap", 4000)
    cmd = [sys.executable, str(CHECK), *paths, *spec["check"], "--jobs", str(jobs), "--timeout", str(timeout), "--work", str(work / "work"), "--out", str(work / "report.json"), "--sdcpi", args.bin, "--set-cap", str(set_cap)]
    out["command"] = " ".join(cmd)
    rc = sh(cmd, work / "check.log", env)
    out["rc"] = rc
    out["seconds"] = round(time.time() - started, 1)
    if not rep.exists():
        out["error"] = f"check.py exit {rc} and no report, see {work / 'check.log'}"
        return out
    return read_report(out, rep, work, started)


def read_report(out: dict, rep: Path, work: Path, started: float) -> dict:
    out["seconds"] = round(time.time() - started, 1)
    j = json.loads(rep.read_text())
    out["instances"] = j["instances"]
    out["runs"] = j["runs"]
    out["counts"] = j["counts"]
    out["failures"] = [
        {"name": r["name"], "text": r["text"], "check": f["check"], "detail": f["detail"]}
        for r in j["results"] for f in r["failures"]
    ]
    out["skipped"] = [
        {"name": r["name"], "check": s["check"], "detail": s["detail"]}
        for r in j["results"] for s in r["skipped"]
    ]
    out["oracle_notes"] = sum(1 for r in j["results"] for n in r["notes"] if "the exact frontier has" in n)
    out["exact_pass_notes"] = sum(1 for r in j["results"] for n in r["notes"] if "states in the exact pass" in n)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin", default=os.environ.get("SDCPI_BIN") or str(HERE.parents[1] / "target" / "release" / "sdcpi"))
    ap.add_argument("--work", default=str(HERE / "work"))
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--timeout", type=float, default=None, help="seconds per call of the binary, for every battery (default: each its own)")
    ap.add_argument("--only", default="a,b,c,d")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--set-cap", type=int, default=None, help="vectors a set of the exact frontier oracle may hold, for every battery (default: 4000, battery b 300)")
    ap.add_argument("--resume", action="store_true", help="keep the batteries whose report.json is in the work folder")
    args = ap.parse_args()
    if not Path(args.bin).exists():
        print(f"run.py: no binary at {args.bin}; build it or pass --bin", file=sys.stderr)
        return 2
    if not CHECK.exists() or not GEN.exists():
        print(f"run.py: {CHECK} or {GEN} is missing", file=sys.stderr)
        return 2
    Path(args.work).mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["SDCPI_BIN"] = args.bin
    keys = [k.strip() for k in args.only.split(",") if k.strip()]
    for k in keys:
        if k not in BATTERIES:
            print(f"run.py: no battery {k!r}", file=sys.stderr)
            return 2

    results = []
    for k in keys:
        spec = BATTERIES[k]
        print(f"[{k}] {spec['title']}", flush=True)
        res = run_battery(k, spec, args, env)
        results.append(res)
        if "error" in res:
            print(f"    ERROR {res['error']}", flush=True)
            continue
        made = sum(res["counts"].values())
        print(f"    {res['instances']} instances, {res['runs']} calls, {'resumed' if res.get('resumed') else str(res['seconds']) + 's'}, checks {made}, failed {len(res['failures'])}, skipped {len(res['skipped'])}, exit {res.get('rc', '-')}", flush=True)
        print("    made: " + ", ".join(f"{c} {n}" for c, n in sorted(res["counts"].items())), flush=True)
        print(f"    oracle of the directed frontier: {res['counts'].get('dir-frontier', 0)} comparisons made ({res['oracle_notes']} frontiers computed); exact passes {res['exact_pass_notes']}", flush=True)
        for f in res["failures"]:
            print(f"    FAIL {f['name']} {f['check']}: {f['detail']}\n         {f['text']}", flush=True)
        for s in res["skipped"]:
            print(f"    skip {s['name']} {s['check']}: {s['detail']}", flush=True)

    checks = sum(sum(r.get("counts", {}).values()) for r in results)
    failed = sum(len(r.get("failures", [])) for r in results)
    skipped = sum(len(r.get("skipped", [])) for r in results)
    errors = [r for r in results if "error" in r]
    passed = checks - failed
    print(f"\nchecks {checks}, passed {passed}, failed {failed}, skipped {skipped}" + (f", batteries in error {len(errors)}" if errors else ""))
    summary = Path(args.work) / "summary.json"
    summary.write_text(json.dumps({"bin": args.bin, "checks": checks, "passed": passed, "failed": failed, "skipped": skipped, "batteries": results}, indent=1))
    print(f"summary: {summary}")
    return 1 if failed or errors else 0


if __name__ == "__main__":
    sys.exit(main())
